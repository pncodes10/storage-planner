def dt(y, m, d, h=11):
    return datetime.datetime(y, m, d, h, rng("dtm", y, m, d).randint(0, 59), tzinfo=IST)


def pdf_bytes(draw):
    b = io.BytesIO()
    c = canvas.Canvas(b, pagesize=A4, invariant=1)
    draw(c)
    c.save()
    return b.getvalue()


def bank_statement(r, name, acct, year, month, opening):
    state = {"bal": opening}

    def draw(c):
        W, H = A4
        c.setFillColorRGB(0.1, 0.25, 0.55); c.rect(0, H - 90, W, 90, fill=1, stroke=0)
        c.setFillColorRGB(1, 1, 1); c.setFont("Helvetica-Bold", 20); c.drawString(40, H - 55, "SPECIMEN BANK LTD.")
        c.setFont("Helvetica", 10); c.drawString(40, H - 75, "Account Statement — synthetic test document")
        c.setFillColorRGB(0, 0, 0); c.setFont("Helvetica", 11)
        c.drawString(40, H - 120, f"Account holder: {name}")
        c.drawString(40, H - 136, f"Account no: XXXXXXXX{acct}    IFSC: SPEC0001234")
        c.drawString(40, H - 152, f"Statement period: 01/{month:02d}/{year} - 28/{month:02d}/{year}")
        y = H - 190
        c.setFont("Helvetica-Bold", 10)
        for x, t in ((40, "Date"), (110, "Description"), (350, "Debit"), (420, "Credit"), (490, "Balance")):
            c.drawString(x, y, t)
        c.setFont("Helvetica", 9)
        bal = state["bal"]
        for i in range(r.randint(18, 34)):
            y -= 15
            if y < 60:
                c.showPage(); c.setFont("Helvetica", 9); y = H - 60
            amt = round(r.uniform(50, 9000), 2)
            credit = r.random() < 0.2
            bal += amt if credit else -amt
            desc = r.choice(["UPI/KIRANA/", "NEFT/SALARY/", "ATM WDL/", "UPI/ELECTRICITY/", "POS/PETROL/",
                             "IMPS/RENT/", "UPI/MEDICAL/", "ACH/SIP MF/"]) + str(r.randint(10 ** 8, 10 ** 9))
            c.drawString(40, y, f"{min(28, i + 1):02d}/{month:02d}/{year}"); c.drawString(110, y, desc)
            c.drawRightString(400, y, "" if credit else f"{amt:,.2f}")
            c.drawRightString(470, y, f"{amt:,.2f}" if credit else "")
            c.drawRightString(560, y, f"{bal:,.2f}")
        c.setFont("Helvetica-Oblique", 8); c.drawString(40, 30, "SPECIMEN — not a real bank document")
        state["bal"] = bal
    data = pdf_bytes(draw)
    return data, state["bal"]


def simple_doc(title, paras, footer="SPECIMEN — synthetic test document"):
    def draw(c):
        W, H = A4
        c.setFont("Helvetica-Bold", 18); c.drawString(50, H - 70, title)
        c.setFont("Helvetica", 11)
        y = H - 110
        for p in paras:
            words, line = p.split(), ""
            for w in words:
                if c.stringWidth(line + " " + w, "Helvetica", 11) > W - 100:
                    c.drawString(50, y, line); y -= 15; line = w
                    if y < 60:
                        c.showPage(); c.setFont("Helvetica", 11); y = H - 60
                else:
                    line = (line + " " + w).strip()
            c.drawString(50, y, line); y -= 25
        c.setFont("Helvetica-Oblique", 8); c.drawString(50, 30, footer)
    return pdf_bytes(draw)


def encrypt(data, user_pw, owner_pw, alg="AES-256", perms=None):
    r = random.Random(user_pw + owner_pw)
    o1, o2 = secrets.token_bytes, os.urandom
    secrets.token_bytes = lambda n=32: bytes(r.randrange(256) for _ in range(n))
    os.urandom = lambda n: bytes(r.randrange(256) for _ in range(n))
    try:
        w = pypdf.PdfWriter(clone_from=pypdf.PdfReader(io.BytesIO(data)))
        kw = {"algorithm": alg}
        if perms is not None:
            kw["permissions_flag"] = perms
        w.encrypt(user_pw, owner_pw, **kw)
        b = io.BytesIO(); w.write(b)
        return b.getvalue()
    finally:
        secrets.token_bytes, os.urandom = o1, o2


def image_pdf(images):
    b = io.BytesIO()
    ims = [i.convert("RGB") for i in images]
    ims[0].save(b, "PDF", save_all=True, append_images=ims[1:], resolution=150, title="scan",
                creationDate=time.gmtime(1704067200), modDate=time.gmtime(1704067200), producer="v2dataset")
    return b.getvalue()


def ooxml(B, rel, obj, **meta):
    p = B._prep(rel)
    obj.save(p)
    normalize_zip(p)
    return B.record(rel, **meta)


