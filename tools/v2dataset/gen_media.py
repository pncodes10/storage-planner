FF = imageio_ffmpeg.get_ffmpeg_exe()
BX = ["-fflags", "+bitexact", "-flags:v", "+bitexact", "-flags:a", "+bitexact", "-map_metadata", "-1",
      "-threads", "1"]
SYN = {"id": "synthetic", "licence": "generated by tools/v2dataset (CC0)"}
X264 = ["-c:v", "libx264", "-preset", "medium", "-pix_fmt", "yuv420p", "-x264-params", "threads=1"]


def ff(*args, inp=None):
    cmd = [FF, "-hide_banner", "-loglevel", "error", "-y", "-filter_threads", "1", "-filter_complex_threads", "1"] + list(args)
    r = subprocess.run(cmd, input=inp, capture_output=True)
    if r.returncode:
        raise RuntimeError(r.stderr.decode()[-800:])


def wav_bytes(samples, sr):
    b = io.BytesIO()
    with wave.open(b, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr)
        w.writeframes((np.clip(samples, -1, 1) * 32000).astype("<i2").tobytes())
    return b.getvalue()


def speechlike(seed, seconds, sr=16000):
    g = np.random.default_rng(seed)
    t = np.arange(int(seconds * sr)) / sr
    f0 = 120 + 60 * g.random() + 20 * np.sin(2 * math.pi * 0.7 * t)
    phase = 2 * math.pi * np.cumsum(f0) / sr
    src = sum(np.sin(k * phase) / k for k in range(1, 12))
    syl = np.zeros_like(t)
    pos = 0.0
    while pos < seconds:
        ln = g.uniform(0.12, 0.35)
        m = (t >= pos) & (t < pos + ln)
        syl[m] = np.sin(math.pi * (t[m] - pos) / ln)
        pos += ln + g.uniform(0.03, 0.4)
    form = np.sin(2 * math.pi * (500 + 300 * np.sin(2 * math.pi * 3 * t)) * t)
    return 0.25 * src * syl * (0.6 + 0.4 * form) + g.normal(0, 0.003, t.shape)


def melody(seed, seconds, sr=44100):
    g = np.random.default_rng(seed)
    scale = [261.6, 293.7, 329.6, 392.0, 440.0, 523.3]
    out = np.zeros(int(seconds * sr))
    i, beat = 0, 0.3
    while i < len(out):
        f = scale[g.integers(len(scale))] * g.choice([0.5, 1, 1])
        n = int(beat * sr)
        tt = np.arange(min(n, len(out) - i)) / sr
        out[i:i + len(tt)] += 0.3 * np.sin(2 * math.pi * f * tt) * np.exp(-3 * tt)
        out[i:i + len(tt)] += 0.1 * np.sin(2 * math.pi * f / 2 * tt)
        i += n
    return out


def build(B):
    S = B.src
    tmp = os.path.join(B.cache, "tmp_media")
    os.makedirs(tmp, exist_ok=True)
    quick = B.quick
    cam = []
    # ---- camera videos from real clips
    clips = [k for k in sorted(S) if S[k]["kind"] == "video"]
    if quick:
        clips = clips[:5]
    for i, sid in enumerate(clips):
        d = rand_dt("vid", sid)
        rel = B.unique(f"DCIM/Camera/VID_{d:%Y%m%d_%H%M%S}.mp4")
        p = B._prep(rel)
        big = i % 5 == 0
        ff("-i", S[sid]["path"], "-t", "40", *X264, "-crf", "14" if big else "23",
           "-c:a", "aac", "-b:a", "128k", *BX, p) if sid != "ocv_megamind" else \
            ff("-i", S[sid]["path"], "-t", "40", *X264, "-crf", "23", "-an", *BX, p)
        B.record(rel, category="video", subcategory="camera_video", tier="NO_LOSS" if big else "KEEP",
                 acceptable=["KEEP", "YOUR_CALL"] if big else ["YOUR_CALL"], importance="medium",
                 scenarios=["S14"] if big else [], synthetic=False,
                 source=B.src_meta(sid, "re-encoded H.264 (first 40s)" + (", high bitrate crf14" if big else "")),
                 date=d, notes="high-bitrate video; can be re-encoded without visible loss" if big else None)
        cam.append(rel)
    # duplicates / re-encodes / WhatsApp
    for j, rel in enumerate(cam[:3]):
        e = B.entries[rel]
        dup = B.unique(f"Movies/{os.path.basename(rel)}")
        B.copy(dup, B.abs(rel), category="video", tier="SAFE", importance="low", scenarios=["S03"],
               rels=[B.rel("EXACT_DUPLICATE", rel)], synthetic=False, source=e["source"], date=rand_dt("vd", rel))
        e["scenarios"] = sorted(set(e["scenarios"]) | {"S03"})
        d = rand_dt("vwa", rel)
        wa = B.unique(f"WhatsApp/Media/WhatsApp Video/Sent/{wa_name(d, B.wa_next(d, 'VID'), 'VID', 'mp4')}")
        ff("-i", B.abs(rel), "-vf", "scale=-2:480", *X264, "-crf", "30", "-c:a", "aac", "-b:a", "64k", *BX,
           B._prep(wa)) if "megamind" not in str(e["source"]) else ff("-i", B.abs(rel), "-vf", "scale=-2:480", *X264,
                                                                       "-crf", "30", *BX, B._prep(wa))
        B.record(wa, category="video", subcategory="whatsapp_copy", tier="SAFE", acceptable=["YOUR_CALL"],
                 importance="low", rels=[B.rel("COMPRESSED_FROM", rel, transform="whatsapp re-encode 480p crf30")],
                 synthetic=False, source=dict(e["source"], transform="whatsapp re-encode"), date=d)
    for j, rel in enumerate(cam[3:5]):
        e = B.entries[rel]
        d = rand_dt("vwa2", rel)
        wa = B.unique(f"WhatsApp/Media/WhatsApp Video/{wa_name(d, B.wa_next(d, 'VID'), 'VID', 'mp4')}")
        ff("-i", B.abs(rel), "-vf", "scale=-2:360", *X264, "-crf", "28", "-an", *BX, B._prep(wa))
        B.record(wa, category="video", subcategory="whatsapp_received", tier="KEEP", acceptable=["YOUR_CALL"],
                 importance="medium", synthetic=False, source=dict(e["source"], transform="re-encode 360p"), date=d,
                 notes="received video; only copy on device")
    # companion subtitle
    if cam:
        srt = os.path.splitext(cam[0])[0] + ".srt"
        B.write_bytes(srt, b"1\n00:00:01,000 --> 00:00:04,000\nSpecimen subtitle\n", category="document",
                      subcategory="subtitle", tier="KEEP", importance="low",
                      rels=[B.rel("COMPANION_OF", cam[0])], source=SYN, date=rand_dt("srt"))
    # corrupted (truncated) video
    if cam:
        data = open(B.abs(cam[1 % len(cam)]), "rb").read()
        d = rand_dt("trunc")
        B.write_bytes(f"DCIM/Camera/VID_{d:%Y%m%d_%H%M%S}.mp4", data[: len(data) * 2 // 5], category="video",
                      subcategory="corrupted_truncated", tier="REVIEW", acceptable=["YOUR_CALL"], importance="low",
                      source=SYN, date=d, notes="truncated MP4 (moov atom missing) — unplayable")
    # ---- screen recording
    F = Fonts(B)
    import gen_synth
    gen_synth.F = F
    for k in range(2 if quick else 3):
        r = rng("screc", k)
        page = chat_screen(r, "Support Chat", [(r.random() < .5, r.choice(PHRASES)) for _ in range(40)],
                           ((236, 229, 221), (7, 94, 84), (220, 248, 198), (255, 255, 255))).resize((540, 1200))
        frames = []
        for f in range(120):
            off = int(min(f, 100) * 4)
            fr = Image.new("RGB", (540, 1200), (255, 255, 255))
            fr.paste(page.crop((0, off, 540, min(1200, off + 1200))), (0, 0))
            frames.append(fr.tobytes())
        d = rand_dt("screc", k)
        rel = f"DCIM/ScreenRecorder/Screen_Recording_{d:%Y%m%d-%H%M%S}.mp4"
        ff("-f", "rawvideo", "-pix_fmt", "rgb24", "-s", "540x1200", "-r", "15", "-i", "-", *X264, "-crf", "26", *BX,
           B._prep(rel), inp=b"".join(frames))
        B.record(rel, category="video", subcategory="screen_recording", tier="YOUR_CALL", acceptable=["KEEP"],
                 importance="low", source=SYN, date=d)
    # ---- S08 long videos with brief meaningful activity
    bases = [rel for rel, e in sorted(B.entries.items()) if rel.startswith("DCIM/Camera/") and e["category"] in
             ("personal_photo", "travel_scenery") and not e["synthetic"] and rel.endswith(".jpg")]
    events = [("Baby's first steps!", 600, 377, 8), ("Package delivered - doorbell cam", 540, 211, 6),
              ("Dashcam: scooter cut-in", 480, 302, 5), ("Grandpa blowing birthday candles", 720, 455, 10)]
    for k, (caption, dur, start, ln) in enumerate(events[:3] if quick else events):
        bg = load_rgb(B.abs(bases[(k * 11) % len(bases)]), 1280).resize((640, 360))
        bgp = os.path.join(tmp, f"bg{k}.png"); bg.save(bgp)
        ov = Image.new("RGBA", (220, 200), (0, 0, 0, 0)); dd = ImageDraw.Draw(ov)
        dd.ellipse((80, 0, 140, 60), fill=(240, 200, 160, 255)); dd.rectangle((85, 60, 135, 150), fill=(200, 40, 40, 255))
        dd.rectangle((85, 150, 105, 200), fill=(40, 40, 120, 255)); dd.rectangle((115, 150, 135, 200), fill=(40, 40, 120, 255))
        ovp = os.path.join(tmp, f"ov{k}.png"); ov.save(ovp)
        tx = Image.new("RGBA", (640, 50), (0, 0, 0, 160)); ImageDraw.Draw(tx).text((12, 8), caption, fill="white",
                                                                                  font=F(28))
        txp = os.path.join(tmp, f"tx{k}.png"); tx.save(txp)
        d = rand_dt("long", k)
        rel = f"DCIM/Camera/VID_{d:%Y%m%d_%H%M%S}.mp4"
        en = f"between(t,{start},{start + ln})"
        fc = (f"[0:v]noise=alls=3:allf=t:all_seed=7,format=yuv420p[b];[b][1:v]overlay=x='(t-{start})*{400 // ln}+60':y=150:"
              f"enable='{en}'[c];[c][2:v]overlay=x=0:y=310:enable='{en}'[v]")
        ff("-loop", "1", "-framerate", "10", "-t", str(dur), "-i", bgp, "-loop", "1", "-framerate", "10", "-i", ovp,
           "-loop", "1", "-framerate", "10", "-i", txp, "-filter_complex", fc, "-map", "[v]", "-t", str(dur),
           *X264, "-crf", "30", "-g", "100", *BX, B._prep(rel))
        B.record(rel, category="video", subcategory="long_static_with_event", tier="KEEP",
                 acceptable=["REVIEW", "PROTECTED"], importance="high", mnd=True, scenarios=["S08"], synthetic=True,
                 source={"id": "composite", "licence": "background derived from " + str(
                     B.entries[bases[(k * 11) % len(bases)]]["source"].get("id")) + "; overlay CC0"},
                 date=d, event={"start_s": start, "end_s": start + ln, "description": caption},
                 duration_s=dur, notes=f"{dur}s mostly static; meaningful activity only at {start}-{start + ln}s")
    d = rand_dt("long_ctl")
    rel = f"DCIM/Camera/VID_{d:%Y%m%d_%H%M%S}.mp4"
    ff("-f", "lavfi", "-i", "color=c=0x101010:s=640x360:r=10:d=300", "-vf", "noise=alls=6:allf=t", *X264, "-crf", "32",
       *BX, B._prep(rel))
    B.record(rel, category="video", subcategory="long_static_no_event", tier="YOUR_CALL", acceptable=["REVIEW", "SAFE"],
             importance="disposable", scenarios=["S08"], source=SYN, date=d, duration_s=300,
             notes="control: 5 min pocket recording, nothing happens")
    # ---- audio
    sp = [k for k in sorted(S) if k.startswith("mpaudio_")]
    for i, sid in enumerate(sp):
        d = rand_dt("rec", sid)
        rel = f"Recordings/Voice Recorder/Recording_{d:%Y%m%d_%H%M%S}.m4a"
        ff("-i", S[sid]["path"], "-c:a", "aac", "-b:a", "96k", *BX, B._prep(rel))
        B.record(rel, category="audio", subcategory="voice_recording", tier="KEEP", importance="medium", synthetic=False,
                 source=B.src_meta(sid, "aac 96k"), date=d)
    for i in range(4 if quick else 18):
        r = rng("ptt", i)
        d = rand_dt("ptt", i)
        sec = r.uniform(3, 45)
        wavp = os.path.join(tmp, f"ptt{i}.wav")
        open(wavp, "wb").write(wav_bytes(speechlike(i, sec), 16000))
        rel = B.unique(f"WhatsApp/Media/WhatsApp Voice Notes/{d:%Y%W}/" + wa_name(d, B.wa_next(d, "PTT"), "PTT", "opus"))
        ff("-i", wavp, "-c:a", "libopus", "-b:a", "24k", *BX, B._prep(rel))
        B.record(rel, category="audio", subcategory="voice_note", tier="KEEP", acceptable=["YOUR_CALL"],
                 importance="medium" if i % 4 == 0 else "low", source=SYN, date=d, notes="speech-like synthetic voice note")
    for i in range(3):
        d = rand_dt("callrec", i)
        wavp = os.path.join(tmp, f"call{i}.wav")
        open(wavp, "wb").write(wav_bytes(speechlike(100 + i, 90 + 30 * i), 16000))
        rel = f"Recordings/Call/Call recording Specimen_{d:%y%m%d_%H%M%S}.m4a"
        ff("-i", wavp, "-c:a", "aac", "-b:a", "48k", *BX, B._prep(rel))
        B.record(rel, category="audio", subcategory="call_recording", tier="KEEP", acceptable=["PROTECTED"],
                 importance="high", source=SYN, date=d)
    # uncompressed WAV (NO_LOSS candidates, also S14 harness)
    for i in range(3):
        d = rand_dt("wav", i)
        rel = f"Recordings/Voice {i + 1:03d}.wav"
        B.write_bytes(rel, wav_bytes(np.concatenate([speechlike(200 + i, 60), melody(i, 60, 16000)]), 16000),
                      category="audio", subcategory="uncompressed_wav", tier="NO_LOSS", acceptable=["KEEP"],
                      importance="medium", scenarios=["S14"], source=SYN, date=d)
    # silence
    for i in range(3):
        d = rand_dt("sil", i)
        rel = f"Recordings/Voice Recorder/Recording_{d:%Y%m%d_%H%M%S}.m4a"
        ff("-f", "lavfi", "-i", f"anullsrc=r=44100:cl=mono", "-t", str(10 + i * 20), "-c:a", "aac", "-b:a", "64k", *BX,
           B._prep(rel))
        B.record(rel, category="audio", subcategory="silence", tier="YOUR_CALL", acceptable=["SAFE", "REVIEW"],
                 importance="disposable", source=SYN, date=d, notes="silent recording (accidental)")
    # music + tones
    music = []
    for i in range(4 if quick else 10):
        d = rand_dt("mus", i)
        wavp = os.path.join(tmp, f"m{i}.wav")
        open(wavp, "wb").write(wav_bytes(melody(1000 + i, 60 + i * 10), 44100))
        rel = f"Music/Specimen Artist/Album {1 + i // 5}/{i + 1:02d} - Specimen Track {i + 1}.mp3"
        ff("-i", wavp, "-c:a", "libmp3lame", "-b:a", "192k", "-id3v2_version", "0", "-write_xing", "0", *BX, B._prep(rel))
        B.record(rel, category="audio", subcategory="music", tier="KEEP", acceptable=["YOUR_CALL"], importance="low",
                 source=SYN, date=d)
        music.append(rel)
    for j, rel in enumerate(music[:2]):
        dup = f"Download/{os.path.basename(rel)}"
        B.copy(dup, B.abs(rel), category="audio", subcategory="music", tier="SAFE", importance="disposable",
               scenarios=["S03"], rels=[B.rel("EXACT_DUPLICATE", rel)], source=SYN, date=rand_dt("md", j))
    for i, (f, n) in enumerate([(880, "Chime"), (660, "Ding"), (440, "Beep")]):
        t = np.arange(int(0.8 * 22050)) / 22050
        wavp = os.path.join(tmp, f"t{i}.wav")
        open(wavp, "wb").write(wav_bytes(0.5 * np.sin(2 * math.pi * f * t) * np.exp(-4 * t), 22050))
        rel = f"Notifications/{n}.ogg"
        ff("-i", wavp, "-c:a", "libvorbis", "-q:a", "3", *BX, B._prep(rel))
        B.record(rel, category="audio", subcategory="tone", tier="KEEP", importance="low", source=SYN,
                 date=rand_dt("tone", i))
