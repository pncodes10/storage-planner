def pick(B, pred, n, key):
    c = sorted(rel for rel, e in B.entries.items() if pred(rel, e))
    r = rng("pick", key)
    return sorted(r.sample(c, min(n, len(c))))


def zbytes(members, stored=False):
    b = io.BytesIO()
    with zipfile.ZipFile(b, "w") as z:
        for name, data in members:
            zip_write(z, name, data, stored=stored)
    return b.getvalue()


def add_scen(B, rel, s):
    B.entries[rel]["scenarios"] = sorted(set(B.entries[rel]["scenarios"]) | {s})


