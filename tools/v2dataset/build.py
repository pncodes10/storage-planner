#!/usr/bin/env python3
"""Build the v2 storage-analysis evaluation dataset.

    python3 tools/v2dataset/build.py --out /home/user/sp-dataset [--cache /home/user/sp-dataset-cache] [--quick]

Re-creates --out from scratch (only if it is empty or was produced by this
script), deterministically.  Downloads are cached in --cache.
"""
import argparse
import collections
import json
import os
import shutil
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import sources  # noqa: E402
from common import Builder, jdump  # noqa: E402

MARKER = ".v2dataset"
DATASET_VERSION = "1.0"


def wipe(out):
    if os.path.exists(out):
        if os.listdir(out) and not os.path.exists(os.path.join(out, MARKER)):
            sys.exit(f"refusing to wipe non-empty {out} that was not produced by build.py")
        # symlink loops etc: rmtree does not follow symlinks
        shutil.rmtree(out)
    os.makedirs(out)
    open(os.path.join(out, MARKER), "w").write("generated by tools/v2dataset/build.py; safe to delete\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="/home/user/sp-dataset")
    ap.add_argument("--cache", default="/home/user/sp-dataset-cache")
    ap.add_argument("--quick", action="store_true", help="smaller build for smoke tests")
    ap.add_argument("--only", default="", help="comma list of generator modules (debug)")
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    t0 = time.time()
    print("[1/4] sources ->", a.cache)
    src = sources.download_all(a.cache)
    print(f"      {len(src)} source items")
    print("[2/4] generating into", out)
    wipe(out)
    B = Builder(out, a.cache, src, quick=a.quick)
    import gen_photos, gen_synth, gen_docs, gen_media, gen_apps, gen_misc  # noqa: E401
    mods = [gen_photos, gen_synth, gen_docs, gen_media, gen_apps, gen_misc]
    only = set(filter(None, a.only.split(",")))
    for m in mods:
        if only and m.__name__ not in only:
            continue
        t = time.time()
        m.build(B)
        print(f"      {m.__name__}: {len(B.entries)} entries total ({time.time() - t:.0f}s)")
    print("[3/4] hashing + mtimes")
    B.finalize()
    print("[4/4] manifest")
    write_outputs(B, out)
    print(f"done: {len(B.entries)} files in {time.time() - t0:.0f}s")


def write_outputs(B, out):
    import scenarios as sc
    entries = [B.entries[k] for k in sorted(B.entries)]
    # validate relationship targets
    for e in entries:
        for r in e["relationships"]:
            assert r["target"] in B.entries, (e["path"], r)
    by_cat = collections.Counter(e["category"] for e in entries)
    by_scen = collections.Counter(s for e in entries for s in e["scenarios"])
    by_tier = collections.Counter(e["expected_tier"] for e in entries)
    total = sum(e["size"] or 0 for e in entries)
    summary = {
        "files": len(entries),
        "total_bytes": total,
        "real": sum(not e["synthetic"] for e in entries),
        "synthetic": sum(e["synthetic"] for e in entries),
        "must_never_delete": sum(e["must_never_delete"] for e in entries),
        "by_category": dict(sorted(by_cat.items())),
        "by_scenario": dict(sorted(by_scen.items())),
        "by_tier": dict(sorted(by_tier.items())),
        "by_relationship": dict(sorted(collections.Counter(
            r["type"] for e in entries for r in e["relationships"]).items())),
    }
    manifest = {
        "dataset": "storage-planner v2 evaluation dataset",
        "version": DATASET_VERSION,
        "generator": "tools/v2dataset/build.py",
        "root": "paths are relative to the dataset root (phone shared storage)",
        "tiers": sc.TIER_DOC,
        "importance_levels": ["critical", "high", "medium", "low", "disposable"],
        "relationship_semantics": sc.REL_DOC,
        "summary": summary,
        "sidecars": sorted(B.extra),
        "files": entries,
    }
    jdump(manifest, os.path.join(out, "manifest.json"))
    jdump(sc.scenarios(B), os.path.join(out, "scenarios.json"))
    for name, obj in B.extra.items():
        if isinstance(obj, str):
            open(os.path.join(out, name), "w").write(obj)
        else:
            jdump(obj, os.path.join(out, name))
    # trimmed sample for git (< 500 KB)
    sample = dict(manifest)
    keep, seen = [], collections.Counter()
    for e in entries:
        k = (e["category"], e["expected_tier"])
        if e["scenarios"] or e["must_never_delete"] or seen[k] < 6:
            keep.append(e)
            seen[k] += 1
    sample["files"] = keep
    sample["note"] = f"trimmed sample: {len(keep)} of {len(entries)} entries; full manifest is in the built dataset"
    sp = os.path.join(HERE, "manifest.sample.json")
    jdump(sample, sp)
    while os.path.getsize(sp) > 480_000 and len(sample["files"]) > 100:
        sample["files"] = sample["files"][::2]
        sample["note"] = f"trimmed sample: {len(sample['files'])} of {len(entries)} entries"
        jdump(sample, sp)
    shutil.copyfile(os.path.join(out, "scenarios.json"), os.path.join(HERE, "scenarios.json"))
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
