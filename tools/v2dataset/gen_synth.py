class Fonts:
    def __init__(self, B):
        self.B = B
        self.cache = {}

    def __call__(self, size, which="sans", bold=False):
        k = (size, which, bold)
        if k not in self.cache:
            p = self.B.src.get("font_" + which, {}).get("path")
            try:
                f = ImageFont.truetype(p, size)
                try:
                    f.set_variation_by_name("Bold" if bold else "Regular")
                except Exception:
                    pass
            except Exception:
                f = ImageFont.load_default(size)
            self.cache[k] = f
        return self.cache[k]


