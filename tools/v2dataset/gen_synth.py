def photograph(r, doc, size=(3000, 4000), seed=0):
    """Place a flat document on a textured surface with perspective + shading."""
    W, H = size
    nrng = np.random.default_rng(seed)
    base = np.array([r.randint(90, 160), r.randint(60, 110), r.randint(30, 70)], np.float32)
    bg = base + nrng.normal(0, 12, (H // 8, W // 8, 1)).astype(np.float32)
    bg = cv2.resize(bg, (W, H), interpolation=cv2.INTER_CUBIC)
    sc = min(W * 0.7 / doc.size[0], H * 0.8 / doc.size[1])
    dw, dh = int(doc.size[0] * sc), int(doc.size[1] * sc)
    docA = np.asarray(doc.resize((dw, dh), Image.LANCZOS)).astype(np.float32)
    x0, y0 = (W - dw) // 2, (H - dh) // 2
    j = lambda: r.uniform(-0.06, 0.06) * W
    src = np.float32([[0, 0], [dw, 0], [dw, dh], [0, dh]])
    dst = np.float32([[x0 + j(), y0 + j()], [x0 + dw + j(), y0 + j()], [x0 + dw + j(), y0 + dh + j()],
                      [x0 + j(), y0 + dh + j()]])
    M = cv2.getPerspectiveTransform(src, dst)
    warped = cv2.warpPerspective(docA, M, (W, H))
    mask = cv2.warpPerspective(np.ones((dh, dw), np.float32), M, (W, H))[..., None]
    out = bg * (1 - mask) + warped * mask
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    shade = 0.75 + 0.3 * (xx / W) * r.uniform(0.5, 1) + 0.1 * (yy / H)
    out = out * shade[..., None] + nrng.normal(0, 4, out.shape)
    return Image.fromarray(np.clip(out, 0, 255).astype(np.uint8))


