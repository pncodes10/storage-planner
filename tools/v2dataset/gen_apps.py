"""APKs and installers (S06, S07) + installed_apps.json.

APKs are minimal valid zip files containing an AndroidManifest.xml stand-in
(plain-text XML, NOT binary AXML), a structurally valid empty classes.dex
header (correct magic/checksum/signature), META-INF signature stand-ins and a
META-INF/v2dataset.properties file with package/versionCode/signer so a test
harness can read identity without aapt.  signing_cert_sha256 = sha256 of
META-INF/CERT.RSA bytes."""
import hashlib
import io
import struct
import zipfile
import zlib

import numpy as np

from common import rand_dt, zip_write

SYN = {"id": "synthetic", "licence": "generated by tools/v2dataset (CC0)"}


def dex():
    h = bytearray(0x70)
    h[0:8] = b"dex\n035\x00"
    struct.pack_into("<I", h, 32, 0x70)  # file_size
    struct.pack_into("<I", h, 36, 0x70)  # header_size
    struct.pack_into("<I", h, 40, 0x12345678)
    h[12:32] = hashlib.sha1(bytes(h[32:])).digest()
    struct.pack_into("<I", h, 8, zlib.adler32(bytes(h[12:])))
    return bytes(h)


def cert(signer):
    return b"0\x82SPECIMEN-CERT:" + hashlib.sha512(("signer:" + signer).encode()).digest() * 8


def apk(pkg, vc, vn, signer, payload_mb, split=None):
    b = io.BytesIO()
    c = cert(signer)
    with zipfile.ZipFile(b, "w") as z:
        man = (f'<?xml version="1.0" encoding="utf-8"?>\n<manifest xmlns:android="http://schemas.android.com/apk/res/android"'
               f' package="{pkg}" android:versionCode="{vc}" android:versionName="{vn}"'
               + (f' split="{split}"' if split else "") + '>\n  <uses-sdk android:minSdkVersion="24" android:targetSdkVersion="34"/>\n'
               '  <application android:label="Specimen"/>\n</manifest>\n')
        zip_write(z, "AndroidManifest.xml", man.encode())
        if not split:
            zip_write(z, "classes.dex", dex())
        zip_write(z, "resources.arsc", b"\x02\x00\x0c\x00" + bytes(64), stored=True)
        g = np.random.default_rng(int(hashlib.sha1(f"{pkg}{vc}{split}".encode()).hexdigest()[:8], 16))
        zip_write(z, "assets/blob.bin", g.integers(0, 256, int(payload_mb * 1e6), dtype=np.uint8).tobytes(), stored=True)
        zip_write(z, "META-INF/MANIFEST.MF", b"Manifest-Version: 1.0\nCreated-By: v2dataset\n")
        zip_write(z, "META-INF/CERT.SF", b"Signature-Version: 1.0\n")
        zip_write(z, "META-INF/CERT.RSA", c)
        zip_write(z, "META-INF/v2dataset.properties",
                  f"package={pkg}\nversionCode={vc}\nversionName={vn}\nsigning_cert_sha256={hashlib.sha256(c).hexdigest()}\n"
                  .encode() + (f"split={split}\n".encode() if split else b""))
    return b.getvalue(), hashlib.sha256(c).hexdigest()


