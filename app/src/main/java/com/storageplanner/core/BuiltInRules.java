package com.storageplanner.core;

import java.util.ArrayList;
import java.util.List;

import com.storageplanner.core.Rule.Action;
import com.storageplanner.core.Rule.Op;
import com.storageplanner.core.Rule.Saving;

/**
 * Today's per-file suggestions, written as rules. Order matters and matches the old hard-coded code: delete
 * rules run top to bottom (a file keeps only its lowest-risk delete, the first one on a tie), then the re-encode
 * rules, of which only the first match counts.
 *
 * Apps and app caches are NOT here: they stay hard-coded in UnitBuilder (rules are for files only, for now).
 * Thresholds (days, bits per pixel, sizes) are condition values, so they can be edited.
 */
public final class BuiltInRules {
    private BuiltInRules() {}

    public static List<Rule> all() {
        List<Rule> l = new ArrayList<Rule>();
        // ---- areas (each file is in one area, so at most one of these can match)
        l.add(del("junk_thumbnails", "Thumbnail cache", Techniques.JUNK, Option.R0, "Thumbnail cache, regenerated by the gallery")
                .when(Tags.AREA, Op.EQ, "thumbnails"));
        l.add(del("stale_temp", "Stale temporary file", Techniques.JUNK, Option.R0, "Stale temporary or partial download")
                .when(Tags.AREA, Op.EQ, "temp").when(Tags.AGE_DAYS, Op.GT, "1"));
        l.add(del("app_residue", "Left behind by an uninstalled app", Techniques.JUNK, Option.R0, "Left behind by uninstalled {pkg}")
                .when(Tags.AREA, Op.EQ, "residue"));
        l.add(del("ext_cache", "App cache on shared storage", Techniques.CACHE, Option.R0, "Cache of {pkg}")      // never matches: the scan skips Android/data
                .when(Tags.AREA, Op.EQ, "ext_cache"));
        l.add(del("expired_status", "Expired chat status", Techniques.JUNK, Option.R0, "Expired WhatsApp status")
                .when(Tags.AREA, Op.EQ, "wa_status").when(Tags.AGE_DAYS, Op.GT, "1"));
        l.add(del("trash", "Already in the trash", Techniques.TRASH, Option.R1, "Already in trash; purge now instead of after 30 days")
                .when(Tags.AREA, Op.EQ, "trash"));
        l.add(del("telegram_media", "Telegram downloaded media", Techniques.TELEGRAM, Option.R1,
                "Re-downloadable from Telegram's cloud (Telegram > Settings > Data and storage > Storage usage)")
                .when(Tags.AREA, Op.EQ, "telegram_media"));
        l.add(del("old_whatsapp_backup", "Older chat backup", Techniques.WA_BACKUP, Option.R1, "Older local chat backup; WhatsApp keeps the newest")
                .when(Tags.AREA, Op.EQ, "wa_old_backup"));
        // ---- what the planner found in the whole scan
        l.add(del("exact_duplicate", "Exact duplicate", Techniques.DUPLICATES, Option.R1, "Identical to {dup_of}")
                .when(Tags.DUPLICATE, Op.IS_YES, ""));
        l.add(del("installer_installed", "Installer, app already installed", Techniques.INSTALLED_APK, Option.R1, "Installer for {app_label}, already installed")
                .when(Tags.INSTALLER_INSTALLED, Op.IS_YES, ""));
        l.add(del("installer_not_installed", "Installer, app not installed", Techniques.OLD_DOWNLOADS, Option.R4, "Installer for an app that is not installed")
                .when(Tags.INSTALLER_NOT_INSTALLED, Op.IS_YES, ""));
        l.add(del("sent_copy", "Sent copy of a camera photo", Techniques.SENT, Option.R1, "Compressed copy of {sent_of}, which is kept")
                .when(Tags.SENT_COPY, Op.IS_YES, ""));
        Rule burst = del("burst_extra", "Extra shot of a burst", Techniques.BURSTS, Option.R4, "")
                .when(Tags.BURST_EXTRA, Op.IS_YES, "");
        burst.whyHook = "burst";                                // the reason lists what is better in the kept shot: needs code
        l.add(burst);
        l.add(del("blurry_photo", "Much blurrier than your other photos", Techniques.BLURRY, Option.R4, "Much softer than your other photos")
                .when(Tags.BLURRY, Op.IS_YES, ""));
        // ---- picture categories (a picture has one category, so these exclude each other)
        l.add(del("otp_screenshot", "Screenshot of a one-time code", Techniques.OTP_SHOTS, Option.R4, "Screenshot of a one-time code, {age} days old")
                .when(Tags.CATEGORY, Op.EQ, PhotoCategory.OTP).when(Tags.AGE_DAYS, Op.GT, "1"));
        l.add(del("old_payment", "Old payment confirmation", Techniques.OLD_PAYMENTS, Option.R4, "Payment confirmation from {age} days ago")
                .when(Tags.CATEGORY, Op.EQ, PhotoCategory.PAYMENT).when(Tags.AGE_DAYS, Op.GT, "90"));
        l.add(del("expired_ticket", "Ticket whose date has passed", Techniques.EXPIRED_TICKETS, Option.R4, "Ticket for {date}, which has passed")
                .when(Tags.CATEGORY, Op.EQ, PhotoCategory.TICKET).when(Tags.DAYS_SINCE_DATE, Op.GT, "7"));
        l.add(del("old_ticket_no_date", "Old ticket without a date", Techniques.EXPIRED_TICKETS, Option.R4, "Ticket saved {age} days ago")
                .when(Tags.CATEGORY, Op.EQ, PhotoCategory.TICKET).when(Tags.DATE_IN_PICTURE, Op.IS_NO, "").when(Tags.AGE_DAYS, Op.GT, "180"));
        l.add(del("old_greeting", "Old greeting image from a chat", Techniques.GREETINGS, Option.R4, "Greeting image received {age} days ago")
                .when(Tags.CATEGORY, Op.EQ, PhotoCategory.GREETING).when(Tags.AGE_DAYS, Op.GT, "7").when(Tags.CHAT_MEDIA, Op.IS_YES, ""));
        l.add(del("accidental_shot", "Accidental shot", Techniques.ACCIDENTAL, Option.R4, "Almost nothing visible in this shot")
                .when(Tags.CATEGORY, Op.EQ, PhotoCategory.ACCIDENTAL));
        // ---- last of the deletes: only when nothing else found a reason for this file
        Rule old = del("old_download", "Old large download", Techniques.OLD_DOWNLOADS, Option.R4, "Download untouched for {age} days")
                .when(Tags.AREA, Op.EQ, "download").when(Tags.AGE_DAYS, Op.GT, num(UnitBuilder.OLD_DOWNLOAD_DAYS))
                .when(Tags.SIZE_BYTES, Op.GE, num(UnitBuilder.OLD_DOWNLOAD_MIN));
        old.onlyIfNoOtherOption = true;
        l.add(old);
        // ---- re-encoding: the first rule that matches a file is the only one used
        l.add(re("reencode_camera_photo", "Re-encode camera photo", Action.REENCODE_PHOTO, Techniques.PHOTOS, Option.R2, Saving.CAMERA_PHOTO,
                "Visually identical at matched quality; {photo_source}")
                .when(Tags.FILE_TYPE, Op.EQ, "jpeg").when(Tags.AREA, Op.IN, "camera,pictures").when(Tags.BITS_PER_PIXEL, Op.GE, "1.0"));
        l.add(re("reencode_chat_image", "Re-encode chat image", Action.REENCODE_PHOTO, Techniques.CHAT_IMAGES, Option.R2, Saving.CHAT_IMAGE,
                "Visually identical at matched quality; {chat_source}")
                .when(Tags.FILE_TYPE, Op.EQ, "jpeg").when(Tags.AREA, Op.IN, "wa_image,wa_sent").when(Tags.BITS_PER_PIXEL, Op.GE, "0.5"));
        l.add(re("lossless_screenshot", "Lossless screenshot", Action.LOSSLESS_IMAGE, Techniques.SCREENSHOTS, Option.R1, Saving.SCREENSHOT_LOSSLESS,
                "Pixel-identical; {screenshot_source}")
                .when(Tags.FILE_TYPE, Op.EQ, "png").when(Tags.AREA, Op.EQ, "screenshot"));
        l.add(re("reencode_video", "Re-encode H.264 video", Action.REENCODE_VIDEO, Techniques.VIDEOS, Option.R2, Saving.VIDEO,
                "H.264 at {mbps} Mbps; HEVC at matched quality (estimate)")        // a saving of 0 (not H.264, low bitrate) gives no option but still ends the chain
                .when(Tags.FILE_TYPE, Op.IN, "mp4,mkv").when(Tags.VIDEO_CODEC, Op.KNOWN, ""));
        l.add(re("reencode_music", "Music to 128 kbps", Action.REENCODE_AUDIO, Techniques.MUSIC, Option.R3, Saving.MUSIC,
                "{kbps} kbps -> 128 kbps; small audible trade-off for some listeners")
                .when(Tags.AREA, Op.EQ, "music").when(Tags.BITRATE_KBPS, Op.GT, "0").when(Tags.FILE_TYPE, Op.KNOWN, ""));
        for (Rule r : l) { String t = FILE_TYPE.get(r.id); if (t != null) r.fileType = t; }
        return l;
    }

    /** Which files each built-in rule is for; the rest are for any file (areas, duplicates, old downloads). */
    private static final java.util.Map<String, String> FILE_TYPE = new java.util.HashMap<String, String>();
    static {
        FILE_TYPE.put("sent_copy", Tags.IMAGE);
        FILE_TYPE.put("burst_extra", Tags.IMAGE);
        FILE_TYPE.put("blurry_photo", Tags.IMAGE);
        FILE_TYPE.put("otp_screenshot", Tags.IMAGE);
        FILE_TYPE.put("old_payment", Tags.IMAGE);
        FILE_TYPE.put("expired_ticket", Tags.IMAGE);
        FILE_TYPE.put("old_ticket_no_date", Tags.IMAGE);
        FILE_TYPE.put("old_greeting", Tags.IMAGE);
        FILE_TYPE.put("accidental_shot", Tags.IMAGE);
        FILE_TYPE.put("installer_installed", Tags.APK);
        FILE_TYPE.put("installer_not_installed", Tags.APK);
        FILE_TYPE.put("reencode_camera_photo", "jpeg");
        FILE_TYPE.put("reencode_chat_image", "jpeg");
        FILE_TYPE.put("lossless_screenshot", "png");
        FILE_TYPE.put("reencode_video", Tags.VIDEO);
        FILE_TYPE.put("reencode_music", Tags.AUDIO);
    }

    private static Rule del(String id, String name, String technique, int risk, String why) { return rule(id, name, Action.DELETE, technique, risk, Saving.FILE_SIZE, why); }
    private static Rule re(String id, String name, Action a, String technique, int risk, Saving s, String why) { return rule(id, name, a, technique, risk, s, why); }

    private static Rule rule(String id, String name, Action a, String technique, int risk, Saving s, String why) {
        Rule r = new Rule();
        r.id = id; r.name = name; r.builtIn = true; r.action = a; r.technique = technique; r.risk = risk; r.saving = s; r.why = why;
        return r;
    }

    private static String num(double v) { return v == Math.rint(v) ? String.valueOf((long) v) : String.valueOf(v); }
}
